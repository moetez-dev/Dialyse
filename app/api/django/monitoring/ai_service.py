SEVERITY_LEVELS = {
    "HIGH": "critique",
    "RED": "critique",
    "CRITIQUE": "critique",
    "CRITICAL": "critique",
    "SEVERE": "critique",
    "MEDIUM": "avertissement",
    "YELLOW": "avertissement",
    "ATTENTION": "avertissement",
    "ALERTE": "avertissement",
    "WARNING": "avertissement",
    "WARN": "avertissement",
}


def build_alert_guidance(parameter, severity, measured_value, unit, threshold, threshold_type):
    """Build conservative, parameter-specific checks from persisted alert fields.

    These checks are not generated by an AI model and are not a substitute for
    a medically validated local protocol.
    """
    severity_label = SEVERITY_LEVELS.get((severity or "").upper())
    valid_measurement = (
        isinstance(measured_value, (int, float))
        and not isinstance(measured_value, bool)
        and math.isfinite(measured_value)
    )
    valid_threshold = (
        isinstance(threshold, (int, float))
        and not isinstance(threshold, bool)
        and math.isfinite(threshold)
    )
    valid_threshold_type = threshold_type in {
        "normal_min", "normal_max", "critical_min", "critical_max"
    }
    threshold_is_critical = (
        isinstance(threshold_type, str)
        and threshold_type.startswith("critical_")
    )
    threshold_is_normal = (
        isinstance(threshold_type, str)
        and threshold_type.startswith("normal_")
    )
    severity_matches_threshold = (
        severity_label == "critique"
        and threshold_is_critical
    ) or (
        severity_label == "avertissement"
        and threshold_is_normal
    )
    measurement_crosses_threshold = (
        valid_measurement
        and valid_threshold
        and valid_threshold_type
        and (
            measured_value < threshold
            if threshold_type.endswith("_min")
            else measured_value > threshold
        )
    )

    if (
        parameter not in ALERT_GUIDANCE_RULES
        or severity_label is None
        or not valid_measurement
        or not valid_threshold
        or unit != ALERT_PARAMETER_UNITS.get(parameter)
        or not valid_threshold_type
        or not severity_matches_threshold
        or not measurement_crosses_threshold
    ):
        # Aucune valeur mesurée exploitable : on ne rattache aucun conseil.
        # Une alerte antérieure à l'enregistrement des valeurs structurées
        # (donc sans paramètre, ni valeur, ni seuil) reste consultable, mais
        # n'affiche pas de recommandation inventée.
        return {
            "status": "unavailable",
            "source": "Règle interne non générée par IA",
            "cause": (
                "Cette alerte ne contient aucune valeur mesurée exploitable "
                "(paramètre, valeur ou seuil absent ou incohérent) : aucun "
                "conseil ne peut lui être rattaché."
            ),
            "recommendations": [],
            "urgent_escalation": severity_label == "critique",
        }

    operator = "<" if threshold_type.endswith("_min") else ">"
    threshold_class = "critique" if threshold_type.startswith("critical_") else "avertissement"
    reference = f"{operator} {threshold:g} {unit} ({threshold_class})"
    parameter_label = ALERT_PARAMETER_LABELS[parameter]
    recommendations = [
        ALERT_GUIDANCE_RULES[parameter],
        "Comparer la mesure enregistrée au seuil configuré pour cette séance; ne pas modifier une prescription sur la seule base de cette alerte.",
        "Appliquer le protocole clinique local correspondant; ces contrôles génériques nécessitent une validation médicale.",
    ]

    return {
        "status": "ready",
        "source": "Règle interne prédéfinie — non générée par IA; validation médicale requise",
        "cause": (
            f"Mesure de {parameter_label} : {measured_value:g} {unit}, "
            f"seuil déclencheur {reference}, gravité {severity_label}."
        ),
        "recommendations": recommendations,
        "urgent_escalation": severity_label == "critique",
    }


def analyze_measurement(measurement: dict) -> dict:
    """
    Analyze dialysis measurements using local Ollama model.

    IMPORTANT:
    This AI analysis is advisory only.
    Safety threshold alerts remain handled separately
    by monitoring/alerte.py.
    """

    prompt = f"""
You are an AI assistant for a dialysis machine monitoring system.

Analyze the following machine measurements:

Qb: {measurement.get("Qb")}
PA: {measurement.get("PA")}
PTM: {measurement.get("PTM")}
PV: {measurement.get("PV")}
UF_rate: {measurement.get("UF_rate")}
UF_volume: {measurement.get("UF_volume")}
Heparin: {measurement.get("Heparin")}

Provide a short clinical-support analysis.

IMPORTANT:
- Do NOT diagnose the patient.
- Do NOT replace a doctor or nurse.
- Do NOT invent measurements.
- Identify potentially abnormal values.
- Give a concise recommendation for healthcare staff.

Return ONLY valid JSON in this exact format:

{{
  "risk_level": "LOW",
  "analysis": "short explanation",
  "recommendation": "short recommendation"
}}

risk_level must be one of:
LOW, MEDIUM, HIGH
"""

    payload = {
        "model": OLLAMA_MODEL,
        "messages": [
            {
                "role": "user",
                "content": prompt,
            }
        ],
        "stream": False,
        "format": "json",
    }

    try:
        response = requests.post(
            OLLAMA_URL,
            json=payload,
            timeout=60,
        )

        response.raise_for_status()

        data = response.json()

        content = data["message"]["content"]

        result = json.loads(content)

        return {
            "success": True,
            "model": OLLAMA_MODEL,
            "risk_level": result.get("risk_level", "LOW"),
            "analysis": result.get("analysis", ""),
            "recommendation": result.get("recommendation", ""),
        }

    except requests.RequestException as exc:
        return {
            "success": False,
            "error": f"Ollama connection error: {exc}",
        }

    except (KeyError, TypeError, json.JSONDecodeError) as exc:
        return {
            "success": False,
            "error": f"Invalid Ollama response: {exc}",
        }